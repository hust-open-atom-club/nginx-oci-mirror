package main

import (
	"context"
	"errors"
	"fmt"
	"io"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"strings"
)

const nginxHeader = "# Generated by nginx-oci-mirror. Changes are overwritten.\n"

func nginxConfig(ctx context.Context, dir, path string, workers int, progress io.Writer) (int64, error) {
	dir, err := filepath.Abs(dir)
	if err != nil {
		return 0, err
	}
	if strings.ContainsAny(dir, "$\r\n") {
		return 0, errors.New("nginx root cannot contain '$' or newlines")
	}
	if data, err := os.ReadFile(path); err == nil {
		if !strings.HasPrefix(string(data), nginxHeader) {
			return 0, fmt.Errorf("refusing to overwrite existing nginx config %q not generated by this tool", path)
		}
	} else if !errors.Is(err, os.ErrNotExist) {
		return 0, err
	}
	var config strings.Builder
	config.WriteString(nginxHeader)
	fmt.Fprintf(&config, `# Include inside an existing server block.
location ^~ /v2/ {
    root "%s";
    types {}
    default_type application/octet-stream;
    sendfile on;
    gzip off;
    location = /v2/ {
        if ($request_method !~ "^(GET|HEAD)$") { return 405; }
        default_type application/json;
        add_header Docker-Distribution-API-Version registry/2.0 always;
        return 200 "{}";
    }
    location ~ "^/v2/.+/blobs/(sha256:[a-f0-9]{64}|sha512:[a-f0-9]{128})$" {
        set $nginx_oci_blob_digest $1;
        if ($request_method !~ "^(GET|HEAD)$") { return 405; }
        add_header Docker-Distribution-API-Version registry/2.0;
        add_header Docker-Content-Digest $nginx_oci_blob_digest;
        try_files $uri =404;
    }
`, strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(filepath.ToSlash(dir)))
	repositories, total, err := localManifests(ctx, dir, workers, progress)
	if err != nil {
		return 0, err
	}
	for _, repo := range slices.Sorted(maps.Keys(repositories)) {
		if err := ctx.Err(); err != nil {
			return 0, err
		}
		headers := repositories[repo]
		for _, ref := range slices.Sorted(maps.Keys(headers)) {
			desc := headers[ref]
			fmt.Fprintf(&config, `    location = /v2/%s/manifests/%s {
        if ($request_method !~ "^(GET|HEAD)$") { return 405; }
        default_type "%s";
        add_header Docker-Distribution-API-Version registry/2.0;
        add_header Docker-Content-Digest "%s";
        try_files /v2/%s/manifests/%s =404;
    }
`, repo, ref, desc.MediaType, desc.Digest, repo, desc.Digest)
		}
	}
	config.WriteString("    return 404;\n}\n")
	err = atomicFileContext(ctx, path, func(w io.Writer) error {
		if err := ctx.Err(); err != nil {
			return err
		}
		if _, err := io.WriteString(w, config.String()); err != nil {
			return err
		}
		return ctx.Err()
	})
	if err != nil {
		return 0, err
	}
	return total, nil
}
