package main

import (
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"io/fs"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"strings"

	v1 "github.com/google/go-containerregistry/pkg/v1"
	"github.com/google/go-containerregistry/pkg/v1/types"
)

const nginxHeader = "# Generated by nginx-oci-mirror. Changes are overwritten.\n"

func nginxConfig(dir string) error {
	dir, err := filepath.Abs(dir)
	if err != nil {
		return err
	}
	if strings.ContainsAny(dir, "\r\n") {
		return errors.New("nginx root cannot contain newlines")
	}
	path := filepath.Join(dir, "nginx.conf")
	if data, err := os.ReadFile(path); err == nil {
		if !strings.HasPrefix(string(data), nginxHeader) {
			return errors.New("refusing to overwrite an existing nginx.conf not generated by this tool")
		}
	} else if !errors.Is(err, os.ErrNotExist) {
		return err
	}
	var config strings.Builder
	config.WriteString(nginxHeader)
	fmt.Fprintf(&config, `error_log stderr;
pid /tmp/nginx-oci-mirror.pid;
events {}
http {
    access_log /dev/stdout;
    types {}
    default_type application/octet-stream;
    server {
        listen 8080;
        root "%s";
        sendfile on;
        if ($request_method !~ "^(GET|HEAD)$") { return 405; }
        location = /v2/ {
            default_type application/json;
            add_header Docker-Distribution-API-Version registry/2.0 always;
            return 200 "{}";
        }
        location ~ "^/v2/.+/blobs/(sha256:[a-f0-9]{64}|sha512:[a-f0-9]{128})$" {
            add_header Docker-Distribution-API-Version registry/2.0;
            add_header Docker-Content-Digest $1;
            try_files $uri =404;
        }
`, strings.NewReplacer(`\`, `\\`, `"`, `\"`, `$`, `\$`).Replace(filepath.ToSlash(dir)))
	err = filepath.WalkDir(filepath.Join(dir, "v2"), func(path string, entry fs.DirEntry, err error) error {
		if err != nil || entry.IsDir() || entry.Name() != ".metadata.json" {
			return err
		}
		repo, err := filepath.Rel(filepath.Join(dir, "v2"), filepath.Dir(filepath.Dir(path)))
		if err != nil {
			return err
		}
		repo = filepath.ToSlash(repo)
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		var headers map[string]v1.Descriptor
		if err := json.Unmarshal(data, &headers); err != nil {
			return err
		}
		for _, ref := range slices.Sorted(maps.Keys(headers)) {
			desc := headers[ref]
			if !validReference(repo, ref) || !validContent(filepath.Join(filepath.Dir(path), desc.Digest.String()), desc) {
				return fmt.Errorf("invalid manifest metadata for %s:%s", repo, ref)
			}
			switch desc.MediaType {
			case types.OCIImageIndex, types.DockerManifestList, types.OCIManifestSchema1, types.DockerManifestSchema2:
			default:
				return fmt.Errorf("unsupported manifest media type %q", desc.MediaType)
			}
			fmt.Fprintf(&config, `        location = /v2/%s/manifests/%s {
            default_type "%s";
            add_header Docker-Distribution-API-Version registry/2.0;
            add_header Docker-Content-Digest "%s";
            try_files /v2/%s/manifests/%s =404;
        }
`, repo, ref, desc.MediaType, desc.Digest, repo, desc.Digest)
		}
		return nil
	})
	if err != nil {
		return err
	}
	config.WriteString("        location / { return 404; }\n    }\n}\n")
	return atomicFile(path, func(w io.Writer) error { _, err := io.WriteString(w, config.String()); return err })
}
